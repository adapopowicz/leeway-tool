# Builds the four shirt images used by the mockup and bundles them into assets/shirt.js
#   front / back  ×  fitted (warped to the size-guide measurements, 16 px/cm)  /  original photo
# Run from the repo root:  python3 tools/make_back_photo.py && python3 tools/build_shirt_assets.py
import base64, io, json
from PIL import Image
import numpy as np
from skimage.transform import PiecewiseAffineTransform, warp

C = 299
def rgba_from_photo(path):
    im = np.asarray(Image.open(path).convert('RGB')).astype(float) / 255
    d = 1 - im.min(axis=2)
    alpha = np.clip((d - 0.03) / 0.25, 0, 1)
    body = np.array([108, 82, 76]) / 255
    a3 = alpha[..., None]
    rgb = np.where(a3 > 0, (im - (1 - a3)) / np.maximum(a3, 1e-3), body)
    return np.dstack([np.clip(rgb, 0, 1), alpha])

# photo px  ->  spec cm (origin centre front, y = 0 at HPS). Right half; mirrored for the left.
R = [((405,133),(22.25,2.3)),((460,152),(34,4.5)),((514.5,250),(41.9,13.9)),((569,348),(49.75,23.3)),
     ((510.5,375),(41.6,25.65)),((452,402),(33.5,28)),((452,520),(33.5,51.5)),((452,639),(33.5,75)),((452,250),(33.5,14)),
     ((349.5,110.5),(10.5,0)),((337.5,155),(7.7,7.3)),((344.5,137.5),(9.2,4.4)),((375,639),(16.75,75)),((375,402),(16.75,28)),((375,250),(17,14))]
PTS = []
for p, s in R:
    PTS += [(p, s), ((2*C - p[0], p[1]), (-s[0], s[1]))]
PTS += [((C,166),(0,9)),((C,121),(0,1.6)),((C,98),(0,-1.2)),((C,402),(0,28)),((C,520),(0,51.5)),((C,639),(0,75)),((C,250),(0,14)),((C,660),(0,77.5))]
PTS += [((20,90),(-56,-3)),((578,90),(56,-3)),((20,660),(-56,77.5)),((578,660),(56,77.5)),((C,80),(0,-3)),((470,660),(36,77.5)),((128,660),(-36,77.5)),((590,360),(53,24)),((8,360),(-53,24)),((480,420),(36,30)),((118,420),(-36,30))]
PX, X0, Y0 = 16, -56, -3
W, H = int(112*PX), int(80.5*PX)
src = np.array([p for p, s in PTS], float)
dst = np.array([((s[0]-X0)*PX, (s[1]-Y0)*PX) for p, s in PTS], float)
T = PiecewiseAffineTransform.from_estimate(dst, src)

def webp_b64(arr, q=88):
    b = io.BytesIO()
    Image.fromarray((np.clip(arr, 0, 1) * 255).astype(np.uint8), 'RGBA').save(b, 'WEBP', quality=q)
    open_path = None
    return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()

out = {}
for side, path in [('front', 'assets/shirt-front-original.png'), ('back', 'assets/shirt-back-original.png')]:
    rgba = rgba_from_photo(path)
    fit = warp(rgba, T, output_shape=(H, W), order=1, cval=0)
    out[side] = {'fit': webp_b64(fit), 'orig': webp_b64(rgba, 92)}
    print(side, 'done')
open('assets/shirt.js', 'w').write(
    '/* Auto-generated by tools/build_shirt_assets.py — Blaster 2.0 (M) front/back, fitted (to scale) and original photos. */\n'
    'window.LW_SHIRT_IMGS = ' + json.dumps(out) + ';\n')
print('wrote assets/shirt.js')
