#!/usr/bin/env node
// Bundles every .svg in ./designs into designs/designs.js so the tool works
// when index.html is opened straight from disk (no server needed).
//
//   node scripts/build-designs.mjs
//
// Optional: pass another folder, e.g. node scripts/build-designs.mjs ~/Desktop/Leeway/Designs
// (files are copied into ./designs first).
import { readdirSync, readFileSync, writeFileSync, copyFileSync, chmodSync } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'designs');
const extra = process.argv[2];
if (extra) {
  for (const f of readdirSync(extra).filter((f) => f.toLowerCase().endsWith('.svg'))) {
    copyFileSync(join(extra, f), join(dir, f));
    try { chmodSync(join(dir, f), 0o644); } catch {}
    console.log('copied', f);
  }
}
const files = readdirSync(dir)
  .filter((f) => f.toLowerCase().endsWith('.svg'))
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
const list = files.map((f) => ({
  id: 'd_' + basename(f, '.svg').replace(/[^a-z0-9]+/gi, '_').toLowerCase(),
  name: basename(f, '.svg'),
  file: f,
  svg: readFileSync(join(dir, f), 'utf8'),
}));
writeFileSync(
  join(dir, 'designs.js'),
  '/* Auto-generated by scripts/build-designs.mjs — do not edit by hand. */\nwindow.LW_DESIGNS = ' +
    JSON.stringify(list, null, 0) + ';\n'
);
console.log(`Bundled ${list.length} design(s) into designs/designs.js`);
